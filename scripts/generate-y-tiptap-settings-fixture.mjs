// Writes spec/relaymark/editor/y-tiptap-settings-v1.json: the Y attributes that STOCK @tiptap/y-tiptap
// (the web editor's binding) writes for question and option nodes. Every relaymark runtime must encode
// the same nodes to exactly these attributes.
//
//   node scripts/generate-y-tiptap-settings-fixture.mjs /path/to/relay-elixir/assets
//
// The assets directory supplies @tiptap/y-tiptap, yjs and prosemirror-model (one copy of each, as the web uses).
import {createRequire} from 'node:module';
import {readFileSync,writeFileSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const assets=resolve(process.argv[2]??'');
const require=createRequire(resolve(assets,'package.json'));
const Y=require('yjs'),{Schema,Node}=require('prosemirror-model'),{updateYFragment}=require('@tiptap/y-tiptap');
const version=JSON.parse(readFileSync(resolve(assets,'node_modules/@tiptap/y-tiptap/package.json'),'utf8')).version;
const spec=JSON.parse(readFileSync(resolve(root,'spec/relaymark/editor-schema.json'),'utf8'));
const schema=new Schema({
 topNode:spec.top,
 nodes:Object.fromEntries(spec.nodes.map(({name,markSet,...rest})=>[name,{...rest,...(markSet===null?{}:{marks:markSet.join(' ')})}])),
 marks:Object.fromEntries(spec.marks.map(({name,excludes,...rest})=>[name,{...rest,excludes:excludes.join(' ')}]))
});

const hard={max_files:3,nested:{list:[1,{a:null},'x'],flag:false,deep:{'':0}},'':'empty key','naïve 🌍':'unicode','settings:eA':true,empty:{},none:null};
const label=id=>({type:'questionLabel',attrs:{relaymarkId:id},content:[{type:'text',text:'Q'}]});
const option=(id,attrs)=>({type:'questionOption',attrs:{relaymarkId:id,...attrs},content:[{type:'text',text:'A'}]});
const question=(id,attrs,options)=>({type:'questionBlock',attrs:{relaymarkId:id,...attrs},content:[label(id.replace(/1$/,'9')),...options]});
const docs=[
 ['settings with nested values, empty and unicode keys',[question('b00000000000040008000000000000001',{id:'evidence',type:'file_upload',required:true,points:2,settings:hard},[option('b00000000000040008000000000000011',{id:'a',correct:true,points:1,settings:{weight:2,'':null}})])]],
 ['default (absent) settings',[question('b00000000000040008000000000000021',{},[option('b00000000000040008000000000000031',{})])]],
 ['explicitly empty settings',[question('b00000000000040008000000000000041',{id:'empty',settings:{}},[option('b00000000000040008000000000000051',{settings:{}})])]]
];

const cases=[];
for(const [title,content] of docs){
 const pm=Node.fromJSON(schema,{type:'doc',content});
 const ydoc=new Y.Doc(),fragment=ydoc.get('default',Y.XmlFragment);
 updateYFragment(ydoc,fragment,pm,{mapping:new Map(),isOMark:new Map()});
 const walk=node=>{
  if(!(node instanceof Y.XmlElement))return;
  if(['questionBlock','questionOption'].includes(node.nodeName))cases.push({title,node:node.nodeName,attributes:JSON.parse(JSON.stringify(node.getAttributes()))});
  node.toArray().forEach(walk);
 };
 fragment.toArray().forEach(walk);
}
// attributes are the authored PM attributes (schema defaults applied), y_attributes what y-tiptap stored.
const out={
 fixture_version:1,
 description:`Generated by scripts/generate-y-tiptap-settings-fixture.mjs from stock @tiptap/y-tiptap ${version}: the Y attributes it writes for question and option nodes (null attributes omitted, settings stored as the one object). encode_attributes must equal them.`,
 cases:cases.map(({title,node,attributes},i)=>({name:`y-tiptap writes ${node} (${title}) #${i+1}`,job:'encode_attributes',options:{name:node},input:null,expected:attributes}))
};
// The authored input is the PM node's attrs with schema defaults; recover it from the same documents.
let index=0;
for(const [,content] of docs){
 const pm=Node.fromJSON(schema,{type:'doc',content});
 pm.descendants(node=>{if(['questionBlock','questionOption'].includes(node.type.name)){out.cases[index++].input=JSON.parse(JSON.stringify(node.attrs));}});
}
writeFileSync(resolve(root,'spec/relaymark/editor/y-tiptap-settings-v1.json'),JSON.stringify(out,null,2)+'\n');
console.log(`${out.cases.length} cases from @tiptap/y-tiptap ${version}`);
